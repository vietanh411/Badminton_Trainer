"""Multi-page PDF analysis report rendered with Matplotlib (no extra dependencies)."""

from __future__ import annotations

import io
import textwrap
from datetime import UTC, datetime

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.backends.backend_pdf import PdfPages  # noqa: E402

from app.services.results import heatmap_object  # noqa: E402
from vision.visualization.court_plot import BG, CYAN, HEAT_CMAP, LIME, LINE, draw_court  # noqa: E402

TEXT = "#e2e8f0"
MUTED = "#94a3b8"


def _fmt(v, unit: str = "", digits: int = 2) -> str:
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "—"
    if isinstance(v, (int, float)):
        return f"{v:.{digits}f}{unit}"
    return str(v)


def _page(pdf: PdfPages, title: str):
    fig = plt.figure(figsize=(8.27, 11.69), dpi=110)  # A4 portrait
    fig.patch.set_facecolor(BG)
    fig.text(0.06, 0.955, "BadmintonVision AI", color=CYAN, fontsize=10, weight="bold")
    fig.text(0.06, 0.93, title, color=TEXT, fontsize=16, weight="bold")
    return fig


def _table(fig, rows: list[tuple[str, str]], x: float, y: float, w: float = 0.4, dy: float = 0.024) -> float:
    for k, v in rows:
        fig.text(x, y, k, color=MUTED, fontsize=8.5)
        fig.text(x + w, y, v, color=TEXT, fontsize=8.5, ha="right", weight="bold")
        y -= dy
    return y


def build_report(session: dict, res: dict) -> bytes:
    summary = res["summary"]
    m = summary["metrics"]
    q = summary["quality"]
    buf = io.BytesIO()
    with PdfPages(buf) as pdf:
        # ---- page 1: overview -------------------------------------------------------------
        fig = _page(pdf, session["name"])
        y = 0.895
        if summary.get("synthetic"):
            fig.text(
                0.06,
                y,
                "SYNTHETIC DEMO DATA — generated by the simulator, not a real player's performance.",
                color="#f97316",
                fontsize=9,
                weight="bold",
            )
            y -= 0.03
        video = summary["video"]
        meta = [
            ("Generated", datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")),
            ("Video", f"{video['width']}×{video['height']} · {video['fps']:.1f} fps · {video['duration_s']:.1f} s"),
            (
                "Analysis",
                f"{summary['analysis']['performance_mode']} mode · {summary['analysis']['fps']:.0f} fps · "
                f"{summary['analysis']['detector']} + {summary['analysis']['tracker']}",
            ),
            ("Pipeline version", summary["pipeline_version"]),
        ]
        y = _table(fig, meta, 0.06, y, w=0.85)
        y -= 0.015
        if m.get("calibrated", True) is False:
            fig.text(0.06, y, textwrap.fill(m["reason"], 100), color="#fbbf24", fontsize=9)
        else:
            fig.text(0.06, y, "Movement", color=CYAN, fontsize=11, weight="bold")
            rows = [
                ("Distance covered", _fmt(m["distance"]["total_m"], " m", 1)),
                ("Distance per minute observed", _fmt(m["distance"]["per_minute_m"], " m/min", 1)),
                ("Mean speed", _fmt(m["speed"]["mean_mps"], " m/s")),
                ("Mean speed while moving", _fmt(m["speed"]["mean_while_moving_mps"], " m/s")),
                ("95th percentile speed", _fmt(m["speed"]["p95_mps"], " m/s")),
                ("Max filtered speed", _fmt(m["speed"]["max_filtered_mps"], " m/s")),
                (
                    "Time moving",
                    f"{_fmt(m['speed']['time_moving_s'], ' s', 1)} ({_fmt((m['speed']['moving_share'] or 0) * 100, '%', 0)})",
                ),
                (
                    "Direction changes",
                    f"{m['direction_changes']} ({_fmt(m['direction_changes_per_minute'], '/min', 1)})",
                ),
                ("Singles zones visited", _fmt(m["zones"]["visited_pct"], "%", 0)),
                ("Area holding 90% of time", _fmt(m.get("heatmap_area_90_m2"), " m²", 1)),
            ]
            y2 = _table(fig, rows, 0.06, y - 0.03, w=0.42)
            fig.text(0.55, y, "Recovery & footwork (proxies)", color=CYAN, fontsize=11, weight="bold")
            fw = m["footwork"]
            rows = [
                ("Movements away from base", str(m["recovery"]["excursions"])),
                ("Median recovery time", _fmt(m["recovery"]["recovery_time_median_s"], " s")),
                ("Time > 1.5 m from base", _fmt((m["recovery"]["far_share"] or 0) * 100, "%", 0)),
                ("Path directness (mean)", _fmt(fw["path_directness_mean"])),
                ("Extra distance (mean)", _fmt(fw["extra_distance_pct_mean"], "%", 1)),
                ("Accel p95", _fmt(fw["peak_acceleration_p95_mps2"], " m/s²", 1)),
                ("Decel p95", _fmt(fw["peak_deceleration_p95_mps2"], " m/s²", 1)),
                ("Smoothness (LDLJ, median)", _fmt(fw["smoothness_ldlj_median"], "", 1)),
                ("Ready-position spread", _fmt(fw["positioning_consistency_m"], " m")),
            ]
            _table(fig, rows, 0.55, y - 0.03, w=0.39)
            y = y2 - 0.02
            comp = m.get("composite")
            if comp and comp.get("score") is not None:
                fig.text(
                    0.06,
                    y,
                    f"Experimental footwork index: {comp['score']:.0f}/100",
                    color=LIME,
                    fontsize=10,
                    weight="bold",
                )
                fig.text(
                    0.06,
                    y - 0.02,
                    textwrap.fill(comp["formula"] + " " + comp["caveat"], 120),
                    color=MUTED,
                    fontsize=6.5,
                    va="top",
                )
                y -= 0.09
        fig.text(0.06, y, "Data quality", color=CYAN, fontsize=11, weight="bold")
        cal = q.get("calibration") or {}
        rows = [
            ("Target tracked in", _fmt(q["target_coverage_pct"], "% of sampled frames", 1)),
            ("Identity links / possible switches", f"{q['identity_links']} / {q['possible_id_switches']}"),
            ("Tracking gaps ≥ 0.5 s", str(q["tracking_gaps"])),
            ("Calibration", f"{cal.get('source') or 'none'} · mean error {_fmt(cal.get('mean_error_m'), ' m', 3)}"),
            (
                "Player selection",
                "automatic (largest near-court track)" if q["selection"]["auto"] else "chosen by user",
            ),
            ("Stroke candidates (experimental)", str(m.get("strokes", {}).get("candidates", 0))),
        ]
        _table(fig, rows, 0.06, y - 0.03, w=0.85)
        fig.text(
            0.06,
            0.04,
            textwrap.fill(
                "Measurements come from a single fixed camera. Positions are foot-contact points mapped through a floor "
                "homography; joint angles are 2-D proxies. Recovery and footwork values are movement proxies without "
                "shot timing. Nothing in this report is a medical assessment.",
                130,
            ),
            color=MUTED,
            fontsize=7,
        )
        pdf.savefig(fig, facecolor=BG)
        plt.close(fig)

        if m.get("calibrated", True) is not False:
            # ---- page 2: heatmap + speed --------------------------------------------------
            fig = _page(pdf, "Court occupancy and speed")
            ax = fig.add_axes([0.06, 0.30, 0.42, 0.6])
            hm, pts = heatmap_object(res)
            draw_court(ax)
            ax.imshow(
                hm.share * 100,
                origin="lower",
                extent=(hm.x_edges[0], hm.x_edges[-1], hm.y_edges[0], hm.y_edges[-1]),
                cmap=HEAT_CMAP,
                alpha=0.9,
                zorder=2,
                interpolation="bilinear",
            )
            ax.set_title("Time-weighted occupancy (whole session)", color=LINE, fontsize=8)
            ax2 = fig.add_axes([0.56, 0.62, 0.38, 0.25])
            pos = res["positions"]
            ax2.plot(pos["t"], pos["speed"], color=CYAN, lw=0.7)
            ax2.set_facecolor(BG)
            ax2.set_xlabel("time (s)", color=MUTED, fontsize=7)
            ax2.set_ylabel("speed (m/s)", color=MUTED, fontsize=7)
            ax2.tick_params(colors=MUTED, labelsize=6)
            for s in ax2.spines.values():
                s.set_color("#334155")
            ax3 = fig.add_axes([0.56, 0.32, 0.38, 0.22])
            zs = m["zones"]["share"]
            names = list(zs)
            ax3.barh(names, [zs[n] * 100 for n in names], color=CYAN)
            ax3.set_facecolor(BG)
            ax3.set_xlabel("% of time in singles half", color=MUTED, fontsize=7)
            ax3.tick_params(colors=MUTED, labelsize=6)
            for s in ax3.spines.values():
                s.set_color("#334155")
            pdf.savefig(fig, facecolor=BG)
            plt.close(fig)

        # ---- page 3: strokes ---------------------------------------------------------------
        fig = _page(pdf, "Stroke events (experimental)")
        strokes = session.get("strokes", [])
        fig.text(
            0.06,
            0.89,
            textwrap.fill(
                "Candidate hitting moments detected from racket-wrist speed peaks. Attributes come from transparent pose "
                "heuristics unless a validated classifier is active. Smash, clear and drop are not distinguished without "
                "shuttle tracking.",
                110,
            ),
            color=MUTED,
            fontsize=8,
            va="top",
        )
        y = 0.83
        header = f"{'time':>7}  {'review':<10} {'height':<10} {'side':<10} {'shot type':<22} {'conf':>5}"
        fig.text(0.06, y, header, color=CYAN, fontsize=7.5, family="monospace")
        for e in strokes[:45]:
            y -= 0.017
            side = e.get("label_stroke_side") or e.get("stroke_side") or "—"
            shot = e.get("label_shot_type") or e.get("shot_type") or "—"
            line = f"{e['t']:7.2f}  {e['review_status']:<10} {str(e.get('height_class') or '—'):<10} {side:<10} {shot:<22} {_fmt(e.get('confidence')):>5}"
            fig.text(0.06, y, line, color=TEXT, fontsize=7.5, family="monospace")
        if len(strokes) > 45:
            fig.text(0.06, y - 0.02, f"… {len(strokes) - 45} more in the CSV/JSON export", color=MUTED, fontsize=7.5)
        pdf.savefig(fig, facecolor=BG)
        plt.close(fig)
    return buf.getvalue()
